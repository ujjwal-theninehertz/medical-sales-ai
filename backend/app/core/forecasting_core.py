def _load_champions():
    """CHAMPIONS[metric][horizon] -> {model, reason}. Only metrics that were
    actually backtested (score_whole_business.py's METRICS list) appear here at all --
    that absence, not a hardcoded "!= net_sales" check, is what makes
    answer_question() refuse an unvalidated metric now."""
    with open(os.path.join(_DATA_DIR, "champions_medical.json")) as f:
        data = json.load(f)
    all_champions, all_results = data["champions"], data["results"]
    out = {}
    for metric, champions in all_champions.items():
        out[metric] = {}
        results = all_results[metric]
        for horizon, model in champions.items():
            if horizon == "year":
                error_pct = abs(results["year"][model]["diff_pct"])
                score = f"{results['year'][model]['diff_pct']:+.1f}% vs. actual"
            else:
                error_pct = results[horizon][model]["mape"]
                score = f"{error_pct:.1f}% MAPE"
            out[metric][horizon] = {
                "model": model,
                "error_pct": round(error_pct, 1),
                "reason": f"{REASONS[model]} — won the {metric}/{horizon}-level "
                          f"2021-2024→2025 backtest ({score}).",
            }
    return out


def _load_dimensional_champions():
    """DIMENSIONAL_CHAMPIONS[dimension][value] -> {model, reason}, from
    score_dimensional.py's backtest (net_sales, monthly grain, across every dimension that
    cleared eda_medical.py's density check). A (dimension, value) pair NOT in here has no
    validated forecast -- that absence is what answer_question() checks, not a hardcoded
    dimension list."""
    try:
        with open(os.path.join(_DATA_DIR, "champions_dimensional.json")) as f:
            data = json.load(f)
    except FileNotFoundError:
        return {}
    out = {}
    for dimension, values in data.items():
        out[dimension] = {}
        for value, info in values.items():
            model = info["champion"]
            score = info["scores"][model]
            out[dimension][value] = {
                "model": model, "error_pct": score,
                "reason": f"{REASONS[model]} — won the {dimension}={value} monthly "
                          f"2021-2024→2025 backtest ({score}% MAPE).",
            }
    return out


def _load_dimensional_yearly_champions():
    """DIMENSIONAL_YEARLY_CHAMPIONS[dimension][value] -> {model, reason}, from
    score_dimensional_yearly.py's backtest -- same values as DIMENSIONAL_CHAMPIONS, but scored
    on the FULL YEAR total (sum 12 predicted months, compare to the real 2025 year total)
    rather than month-to-month error. A value can have a different champion here than in
    DIMENSIONAL_CHAMPIONS -- being accurate month-to-month and being accurate on the annual
    total are different questions. A (dimension, value) pair NOT in here has no validated
    YEAR-level forecast -- answer_question() falls back to the existing next-month-only
    refusal for it. Optional file: returns {} until score_dimensional_yearly.py has been run."""
    try:
        with open(os.path.join(_DATA_DIR, "champions_dimensional_yearly.json")) as f:
            data = json.load(f)
    except FileNotFoundError:
        return {}
    out = {}
    for dimension, values in data.items():
        out[dimension] = {}
        for value, info in values.items():
            model = info["champion"]
            diff = info["diff_pct"][model]
            out[dimension][value] = {
                "model": model, "error_pct": abs(diff),
                "reason": f"{REASONS[model]} — won the {dimension}={value} full-year "
                          f"2021-2024→2025 backtest ({diff:+.1f}% vs. actual).",
            }
    return out


